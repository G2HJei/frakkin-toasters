// Writes src/wire/types.ts from src/wire/schema.json, which the backend exports (./gradlew :backend:exportSchema).
// Records become interfaces, unions become TypeScript unions told apart by `kind` (or `type` for the socket messages),
// enums become unions of their constants. Nothing is written by hand, so `tsc` fails when the UI uses a field that went
// away. Usage: node scripts/gen-types.mjs <schema.json> <types.ts>
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export function identifier(name) {
  return name.replace(/[^A-Za-z0-9_]/g, '_');
}

export function typeOf(ref) {
  const base = baseTypeOf(ref);
  return ref.nullable ? `${base} | null` : base;
}

function baseTypeOf(ref) {
  switch (ref.t) {
    case 'int':
    case 'long':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'string':
      return 'string';
    case 'class':
      return 'string';
    case 'enum':
      return identifier(ref.name);
    case 'var':
      return ref.name;
    case 'cards':
      return 'DeckCard[]';
    case 'list':
    case 'set':
      return `Array<${typeOf(ref.of)}>`;
    case 'map': {
      const key = ref.key.t === 'enum' ? identifier(ref.key.name) : 'string';
      return `Partial<Record<${key}, ${typeOf(ref.value)}>>`;
    }
    case 'ref': {
      const args = ref.args ? `<${ref.args.map(typeOf).join(', ')}>` : '';
      return identifier(ref.name) + args;
    }
    default:
      throw new Error(`Unknown type reference ${JSON.stringify(ref)}`);
  }
}

export function generate(schema) {
  const lines = [
    '// Generated by `npm run gen` from schema.json, which `./gradlew :backend:exportSchema` writes. Do not edit.',
    '/* eslint-disable */',
    '',
    `export const FORMAT_VERSION = ${schema.formatVersion};`,
    '',
  ];
  const names = Object.keys(schema.types).sort();
  const cardTypes = new Set();
  for (const name of names) {
    const type = schema.types[name];
    const id = identifier(name);
    if (type.kind === 'enum') {
      lines.push(`export type ${id} = ${type.values.map((value) => `'${value}'`).join(' | ') || 'never'};`);
      lines.push(`export const ${id}_VALUES: readonly ${id}[] = [${type.values.map((value) => `'${value}'`).join(', ')}];`);
    } else if (type.kind === 'union') {
      lines.push(`export type ${id} = ${type.members.map(identifier).join(' | ') || 'never'};`);
    } else if (type.kind === 'record') {
      // a parameter that only a Class<T> names is a type name on the wire, so the TypeScript doesn't need it
      const used = (type.typeParams ?? []).filter((parameter) =>
        JSON.stringify(type.components).includes(`"t":"var","name":"${parameter}"`),
      );
      const params = used.length > 0 ? `<${used.join(', ')}>` : '';
      lines.push(`export interface ${id}${params} {`);
      if (type.type) {
        lines.push(`  type: '${type.type}';`);
      } else if (type.tagged) {
        lines.push(`  kind: '${name}';`);
      }
      for (const component of type.components) {
        lines.push(`  ${component.name}: ${typeOf(component.type)};`);
      }
      lines.push('}');
    } else {
      throw new Error(`Unknown kind of type ${name}: ${type.kind}`);
    }
    lines.push('');
    if (['CivilianShip', 'SkillCard'].includes(name)) {
      cardTypes.add(id);
    }
  }
  // the cards of a deck or a pile: an enum constant, a Skill Card or a civilian ship
  lines.push(`export type DeckCard = string | ${[...cardTypes].sort().join(' | ') || 'never'};`);
  lines.push('');
  for (const [list, members] of Object.entries(schema.lists ?? {})) {
    lines.push(`export const ${list.toUpperCase()}: readonly string[] = [${members.map((member) => `'${member}'`).join(', ')}];`);
  }
  lines.push('');
  return lines.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const [schemaFile, typesFile] = process.argv.slice(2);
  const schema = JSON.parse(readFileSync(schemaFile, 'utf8'));
  writeFileSync(typesFile, generate(schema));
  console.log(`Wrote ${typesFile}: ${Object.keys(schema.types).length} types`);
}
